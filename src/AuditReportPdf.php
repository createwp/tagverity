/**
 * Builds the printable version of audit-report.php. The HTML is self-contained with
 * inline CSS only, and uses the subset Dompdf understands (tables and blocks, no flex
 * or grid, no CSS variables). Colours are the app's design tokens, written out as
 * literals. Every dynamic value is escaped before it reaches the markup.
 */
final class AuditReportPdf
{
    private const SCORE_COLOURS = ['#10b981', '#f59e0b', '#ef4444'];

    private const FIX_OWNER_LABELS = [
        'gtm'       => 'GTM',
        'developer' => 'Developer',
        'ga4_admin' => 'GA4 Admin',
        'hosting'   => 'Hosting / DNS',
        'multiple'  => 'Multiple Teams',
    ];

    private const COVERAGE_BADGES = [
        'ok'    => ['class' => 'pill-success', 'label' => 'Checked'],
        'warn'  => ['class' => 'pill-warning', 'label' => 'Not checked'],
        'muted' => ['class' => 'pill-neutral', 'label' => 'Not included'],
    ];

    /**
     * @param array      $job                  audit_jobs row (id, status, health_score, completed_at)
     * @param string     $clientName           client name, unescaped
     * @param list<array> $findings            audit_findings rows, already ordered
     * @param list<array> $coverageRows        AuditCoverageView::describe() output
     * @param bool       $includeDeveloperNotes true only when the plan includes developer notes
     */
    public function html(array $job, string $clientName, array $findings, array $coverageRows, bool $includeDeveloperNotes): string
    {
        $status    = (string) ($job['status'] ?? '');
        $hasScore  = $job['health_score'] !== null;
        $score     = $hasScore ? (int) $job['health_score'] : 0;
        $isUnscoredFinal = in_array($status, ['partial', 'failed'], true);
        $isFailed  = $status === 'failed';

        $grouped = ['critical' => [], 'warning' => [], 'info' => []];
        foreach ($findings as $finding) {
            $severity = (string) ($finding['severity'] ?? 'info');
            if (!isset($grouped[$severity])) {
                $severity = 'info';
            }
            $grouped[$severity][] = $finding;
        }

        $completed = !empty($job['completed_at'])
            ? date('d M Y, H:i', strtotime((string) $job['completed_at']))
            : 'In progress';
        $id = (int) ($job['id'] ?? 0);

        $body  = $this->headerBlock($clientName, $completed, $id);
        $body .= $this->summaryBlock($status, $hasScore, $score, $isFailed, $grouped);

        if ($isUnscoredFinal && !empty($findings)) {
            $body .= '<div class="notice">These findings come from the data we could check. Sources marked &quot;Not checked&quot; above may hide other issues.</div>';
        }

        $body .= $this->coverageBlock($coverageRows, $this->coverageFootnote($job));
        $body .= $this->findingsBlock($status, $findings, $grouped, $includeDeveloperNotes);

        $generated = $this->e(date('d M Y'));
        $body .= '<div class="footer">Generated by TagVerity on ' . $generated . '</div>';

        return '<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">'
            . '<title>Audit report #' . $id . ' - TagVerity</title>'
            . '<style>' . $this->css() . '</style>'
            . '</head><body>' . $body . '</body></html>';
    }

    /**
     * PDF bytes for the report, A4 portrait, no remote assets.
     */
    public function render(array $job, string $clientName, array $findings, array $coverageRows, bool $includeDeveloperNotes): string
    {
        $html = $this->html($job, $clientName, $findings, $coverageRows, $includeDeveloperNotes);

        $options = new \Dompdf\Options();
        $options->set('isRemoteEnabled', false);
        $options->set('defaultFont', 'DejaVu Sans');

        $dompdf = new \Dompdf\Dompdf($options);
        $dompdf->loadHtml($html, 'UTF-8');
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        return $dompdf->output();
    }

    private function headerBlock(string $clientName, string $completed, int $id): string
    {
        return '<table class="band"><tr>'
            . '<td class="band-wordmark">TagVerity</td>'
            . '<td class="band-right">Audit report</td>'
            . '</tr></table>'
            . '<div class="band-accent"></div>'
            . '<h1 class="title">Audit report</h1>'
            . '<div class="subtitle">' . $this->e($clientName) . ' &middot; ' . $this->e($completed)
            . ' &middot; #' . $id . '</div>';
    }

    private function summaryBlock(string $status, bool $hasScore, int $score, bool $isFailed, array $grouped): string
    {
        $scoreCell = '';
        if ($hasScore) {
            $colour = $this->scoreColour($score);
            $scoreCell = '<div class="score-value" style="color:' . $colour . '">' . $score . '</div>'
                . '<div class="score-label" style="color:' . $colour . '">' . $this->e($this->scoreLabel($score)) . '</div>'
                . '<div class="score-caption">Overall health score</div>';
        } elseif (in_array($status, ['partial', 'failed'], true)) {
            $scoreCell = '<div class="score-value muted">&mdash;</div>'
                . '<div class="score-label">Score unavailable</div>'
                . '<div class="score-note">Some data sources couldn\'t be checked, so we can\'t give a trustworthy score yet.</div>'
                . '<div class="score-caption">Overall health score</div>';
        } else {
            $scoreCell = '<div class="score-value muted">&mdash;</div>'
                . '<div class="score-label">' . (in_array($status, ['queued', 'running'], true) ? 'Audit still running' : 'Score unavailable') . '</div>'
                . '<div class="score-caption">Overall health score</div>';
        }

        $count = fn(string $severity): string => $isFailed ? '&mdash;' : (string) count($grouped[$severity]);

        return '<table class="summary"><tr>'
            . '<td class="score-cell">' . $scoreCell . '</td>'
            . '<td class="counts-cell"><table class="counts"><tr>'
            . '<td class="count critical"><div class="count-value">' . $count('critical') . '</div><div class="count-label">Critical findings</div></td>'
            . '<td class="count warning"><div class="count-value">' . $count('warning') . '</div><div class="count-label">Warnings</div></td>'
            . '<td class="count info"><div class="count-value">' . $count('info') . '</div><div class="count-label">Info / best practices</div></td>'
            . '</tr></table></td>'
            . '</tr></table>';
    }

    private function coverageBlock(array $coverageRows, string $footnote = ''): string
    {
        $html = '<div class="section">'
            . '<h2>Data coverage</h2>'
            . '<div class="section-subtitle">Which data sources we could check for this audit</div>'
            . '<table class="coverage">';

        foreach ($coverageRows as $row) {
            $tone  = (string) ($row['tone'] ?? 'warn');
            $badge = self::COVERAGE_BADGES[$tone] ?? self::COVERAGE_BADGES['warn'];
            $label = (string) ($row['status'] ?? '') === 'not_recorded' ? 'Not recorded' : $badge['label'];

            $html .= '<tr>'
                . '<td class="cov-status"><span class="pill ' . $badge['class'] . '">' . $this->e($label) . '</span></td>'
                . '<td class="cov-source">' . $this->e((string) ($row['source'] ?? '')) . '</td>'
                . '<td class="cov-message">' . $this->e((string) ($row['message'] ?? '')) . '</td>'
                . '</tr>';
        }

        return $html . '</table>' . $footnote . '</div>';
    }

    /**
     * The same small print the web report shows under Data coverage. Returns '' when
     * the job has no recorded rule set or GA4 window (for example, jobs from before
     * coverage tracking).
     */
    private function coverageFootnote(array $job): string
    {
        $status = $this->sourceStatus($job);
        if ($status === null) {
            return '';
        }

        $parts = [];
        if (!empty($status['rule_set_version'])) {
            $parts[] = 'Rule set ' . (string) $status['rule_set_version'];
        }
        if (isset($status['ga4_window_days'])) {
            $parts[] = 'GA4 window ' . (int) $status['ga4_window_days'] . ' days';
        }
        if ($parts === []) {
            return '';
        }

        return '<div class="coverage-note">' . $this->e(implode(' · ', $parts)) . '</div>';
    }

    /** Decodes audit_jobs.source_status, which may arrive as a JSON string or an array. */
    private function sourceStatus(array $job): ?array
    {
        $raw = $job['source_status'] ?? null;
        if ($raw === null || $raw === '') {
            return null;
        }
        $decoded = is_array($raw) ? $raw : json_decode((string) $raw, true);

        return is_array($decoded) ? $decoded : null;
    }

    private function findingsBlock(string $status, array $findings, array $grouped, bool $includeDeveloperNotes): string
    {
        if (empty($findings)) {
            return $this->emptyState($status);
        }

        $severityLabels = ['critical' => 'Critical', 'warning' => 'Warnings', 'info' => 'Info / best practices'];
        $html = '<div class="section"><h2>Findings</h2>';

        foreach ($severityLabels as $severity => $heading) {
            if (empty($grouped[$severity])) {
                continue;
            }
            // The heading stays with the first finding so it cannot be orphaned at a page foot.
            $items = $grouped[$severity];
            $first = array_shift($items);
            $html .= '<div class="finding-group"><div class="group-heading">' . $this->e($heading) . ' (' . count($grouped[$severity]) . ')</div>'
                . $this->findingBlock($severity, $first, $includeDeveloperNotes)
                . '</div>';
            foreach ($items as $finding) {
                $html .= $this->findingBlock($severity, $finding, $includeDeveloperNotes);
            }
        }

        return $html . '</div>';
    }

    private function findingBlock(string $severity, array $finding, bool $includeDeveloperNotes): string
    {
        $owner      = (string) ($finding['fix_owner'] ?? '');
        $ownerLabel = self::FIX_OWNER_LABELS[$owner] ?? ucfirst($owner);
        $affected   = (string) ($finding['affected_item'] ?? '');
        $notes      = (string) ($finding['developer_notes'] ?? '');

        $html = '<div class="finding finding-' . $severity . '">'
            . '<div class="finding-tags">'
            . '<span class="pill pill-' . $severity . '">' . strtoupper($severity) . '</span> '
            . '<span class="pill pill-neutral">' . $this->e($ownerLabel) . '</span>'
            . '</div>'
            . '<div class="finding-title">' . $this->e((string) ($finding['title'] ?? '')) . '</div>'
            . '<div class="finding-description">' . $this->e((string) ($finding['description'] ?? '')) . '</div>'
            . '<div class="finding-rec"><span class="rec-label">Recommendation</span><br>'
            . $this->e((string) ($finding['recommendation'] ?? '')) . '</div>'
            . '<div class="finding-meta"><span class="meta-label">Who fixes it:</span> ' . $this->e($ownerLabel) . '</div>';

        if ($affected !== '') {
            $html .= '<div class="finding-meta"><span class="meta-label">Affected:</span> '
                . '<span class="mono">' . $this->e($affected) . '</span></div>';
        }

        if ($includeDeveloperNotes && $notes !== '') {
            $html .= '<div class="dev-notes"><div class="dev-notes-label">Developer notes</div>'
                . $this->e($notes) . '</div>';
        }

        return $html . '</div>';
    }

    private function emptyState(string $status): string
    {
        switch ($status) {
            case 'complete':
                $title = 'No findings — looking great!';
                $text  = 'This audit found no issues with your GTM or GA4 implementation.';
                break;
            case 'partial':
                $title = 'No findings in the data we could check';
                $text  = 'Some data sources couldn\'t be checked, so this isn\'t a clean result. See Data coverage above.';
                break;
            case 'failed':
                $title = 'No findings to report';
                $text  = 'We couldn\'t check the data needed for this audit, so it can\'t tell you whether anything is wrong.';
                break;
            default:
                $title = 'Audit still running';
                $text  = 'Results appear here when the audit finishes.';
        }

        return '<div class="section"><div class="empty">'
            . '<div class="empty-title">' . $this->e($title) . '</div>'
            . '<div class="empty-text">' . $this->e($text) . '</div>'
            . '</div></div>';
    }

    private function scoreColour(int $score): string
    {
        return $score >= 80 ? self::SCORE_COLOURS[0] : ($score >= 50 ? self::SCORE_COLOURS[1] : self::SCORE_COLOURS[2]);
    }

    private function scoreLabel(int $score): string
    {
        return $score >= 80 ? 'Healthy' : ($score >= 50 ? 'Needs Attention' : 'Critical Issues');
    }

    private function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES, 'UTF-8');
    }

